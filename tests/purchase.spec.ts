import { test, expect, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const evidence = 'docs/evidence'
async function capture(page: Page, name: string) {
  await mkdir(evidence, { recursive: true })
  await page.evaluate(() => document.fonts.ready)
  // Aguarda imagens lazy abaixo da dobra para evidências completas.
  await page.locator('img').evaluateAll(images => images.forEach(img => img.loading = 'eager'))
  await expect.poll(() => page.locator('img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0))).toBe(true)
  await page.screenshot({ path: `${evidence}/${name}.png`, fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function fillAddress(page: Page) {
  await page.getByLabel('CEP', { exact: true }).fill('01310-100')
  await page.getByLabel('Rua', { exact: true }).fill('Rua das Flores')
  await page.getByLabel('Número', { exact: true }).fill('321')
  await page.getByLabel('Complemento').fill('Apto 42')
  await page.getByLabel('Bairro', { exact: true }).fill('Vila Nova')
  await page.getByLabel('Cidade', { exact: true }).fill('São Paulo')
  await page.getByLabel('UF', { exact: true }).selectOption('SP')
  await page.getByRole('radio', { name: 'Cartão de crédito', exact: true }).check()
}

test('compra completa, validação, persistência, responsividade e confirmação', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.coffee-card')).toHaveCount(14)
  await capture(page, 'home-desktop')
  await page.getByRole('button', { name: 'Aumentar Expresso Tradicional', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar Expresso Tradicional ao carrinho', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar Latte ao carrinho', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Carrinho com 3 itens' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Carrinho com 3 itens' })).toBeVisible()
  await page.getByRole('link', { name: 'Carrinho com 3 itens' }).click()
  await page.getByRole('button', { name: 'Aumentar Expresso Tradicional', exact: true }).click()
  await expect(page.locator('.grand-total dd')).toHaveText(/46,10/)
  await page.getByRole('button', { name: 'Diminuir Expresso Tradicional', exact: true }).click()
  await expect(page.locator('.grand-total dd')).toHaveText(/36,20/)
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page.getByRole('alert')).toHaveCount(7)
  await expect(page.getByLabel('CEP', { exact: true })).toBeFocused()
  await fillAddress(page)
  await capture(page, 'checkout-desktop')
  await page.setViewportSize({ width: 768, height: 1024 })
  await capture(page, 'checkout-tablet')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture(page, 'checkout-mobile')
  await page.getByRole('button', { name: 'Ativar modo escuro' }).click()
  await capture(page, 'checkout-dark-mobile')
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page).toHaveURL(/\/sucesso$/)
  await expect(page.getByText('Rua das Flores, 321', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Carrinho com 0 itens' })).toBeVisible()
  await expect(page.locator('.receipt-total strong')).toHaveText(/36,20/)
  await capture(page, 'sucesso-dark-mobile')
  await page.reload()
  await expect(page.getByText('Rua das Flores, 321', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Ativar modo claro' }).click()
  await capture(page, 'sucesso-mobile')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await capture(page, 'sucesso-desktop')
  await page.getByRole('link', { name: 'Voltar para os cafés' }).click()
  await page.goto('/checkout')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio.' })).toBeVisible()
  expect(errors).toEqual([])
})

test('home em tablet, mobile, 320px, dark persistente e teclado', async ({ page }) => {
  await page.goto('/')
  await page.setViewportSize({ width: 768, height: 1024 })
  await capture(page, 'home-tablet')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture(page, 'home-mobile')
  await page.getByRole('button', { name: 'Ativar modo escuro' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await capture(page, 'home-dark-mobile')
  await page.setViewportSize({ width: 320, height: 740 })
  await capture(page, 'home-320-dark')
  await page.keyboard.press('Tab')
  await expect(page.locator('.skip-link')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeFocused()
})

test('remove produtos e protege sucesso sem pedido', async ({ page }) => {
  await page.goto('/sucesso')
  await expect(page).toHaveURL(/\/$/)
  await page.getByRole('button', { name: 'Adicionar Expresso Tradicional ao carrinho', exact: true }).click()
  await page.goto('/checkout')
  await page.getByRole('button', { name: 'Remover Expresso Tradicional', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: 'Carrinho com 0 itens' })).toBeVisible()
})

test('JSON corrompido não derruba carrinho nem confirmação', async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('coffee:cart:v1', '{bad'); sessionStorage.setItem('coffee:last-order:v1', '{bad') })
  await page.goto('/checkout')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio.' })).toBeVisible()
  await page.goto('/sucesso')
  await expect(page).toHaveURL(/\/$/)
})

test('storage bloqueado mantém compra disponível e avisa a limitação', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(Storage.prototype, 'setItem', { value: () => { throw new DOMException('Blocked', 'SecurityError') } }) })
  await page.goto('/')
  await expect(page.getByText(/Seu navegador bloqueou o armazenamento\. O carrinho/)).toBeVisible()
  await page.getByRole('button', { name: 'Adicionar Latte ao carrinho', exact: true }).click()
  await page.getByRole('link', { name: 'Carrinho com 1 item', exact: true }).click()
  await fillAddress(page)
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page).toHaveURL(/\/sucesso$/)
  await expect(page.getByText(/Seu navegador bloqueou o armazenamento da sessão/)).toBeVisible()
})
